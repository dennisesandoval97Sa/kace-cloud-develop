import { createHash } from 'node:crypto';
import { v4 as uuidv4 } from 'uuid';
import {
    DeleteObjectCommand,
    GetObjectCommand,
    HeadObjectCommand,
    PutObjectCommand,
    S3Client,
} from '@aws-sdk/client-s3';
import { EmailBodyStoragePort } from '../../domain/ports/EmailBodyStoragePort.js';
import { TenantContext } from '../../../shared/index.js';

const PART_EXTENSIONS = {
    text: 'txt',
    html: 'html',
};

const PART_CONTENT_TYPES = {
    text: 'text/plain; charset=utf-8',
    html: 'text/html; charset=utf-8',
};

export class S3EmailBodyStorage extends EmailBodyStoragePort {
    #s3Client;
    #bucket;
    #region;

    constructor({ s3Client = null, bucket = null, region = null, credentials = null } = {}) {
        super();
        const tenant = TenantContext.getTenant?.();
        const resolvedRegion = region ?? tenant?.aws_s3_region?.value ?? process.env.AWS_S3_REGION;
        const resolvedCredentials = credentials ?? {
            accessKeyId: tenant?.aws_s3_access_key_id?.value ?? process.env.AWS_S3_ACCESS_KEY_ID,
            secretAccessKey: tenant?.aws_s3_secret_access_key?.value ?? process.env.AWS_S3_SECRET_ACCESS_KEY,
        };

        this.#s3Client =
            s3Client ??
            new S3Client({
                region: resolvedRegion,
                credentials: resolvedCredentials,
            });

        this.#bucket = bucket ?? tenant?.aws_s3_bucket?.value ?? process.env.BUCKET ?? process.env.AWS_S3_BUCKET;
        this.#region = resolvedRegion;
    }

    async upload({ emailId, part, buffer, contentType }) {
        const normalizedPart = part === 'html' ? 'html' : 'text';
        const bodyBuffer = Buffer.isBuffer(buffer) ? buffer : Buffer.from(buffer ?? '');
        const extension = PART_EXTENSIONS[normalizedPart];
        const key = `email-bodies/${emailId}/${normalizedPart}-${uuidv4()}.${extension}`;
        const resolvedContentType = contentType ?? PART_CONTENT_TYPES[normalizedPart];

        await this.#s3Client.send(
            new PutObjectCommand({
                Bucket: this.#bucket,
                Key: key,
                Body: bodyBuffer,
                ContentType: resolvedContentType,
            })
        );

        return {
            s3Key: key,
            contentType: resolvedContentType,
            sizeBytes: bodyBuffer.length,
            sha256: createHash('sha256').update(bodyBuffer).digest('hex'),
        };
    }

    async download(s3Key) {
        const response = await this.#s3Client.send(
            new GetObjectCommand({
                Bucket: this.#bucket,
                Key: s3Key,
            })
        );

        const buffer = await this.#bodyToBuffer(response.Body);

        return {
            buffer,
            content: buffer.toString('utf8'),
            contentType: response.ContentType ?? null,
            sizeBytes: buffer.length,
        };
    }

    async head(s3Key) {
        const response = await this.#s3Client.send(
            new HeadObjectCommand({
                Bucket: this.#bucket,
                Key: s3Key,
            })
        );

        return {
            contentType: response.ContentType ?? null,
            sizeBytes: response.ContentLength ?? null,
        };
    }

    extractTenantUploadObjectKey(s3Url) {
        const parsed = new URL(s3Url);

        if (parsed.protocol !== 'https:') {
            throw new Error('External email body URL must use https.');
        }

        if (parsed.search || parsed.hash) {
            throw new Error('External email body URL must not include query string or fragment.');
        }

        const expectedHost = `${this.#bucket}.s3.${this.#region}.amazonaws.com`;
        if (parsed.hostname !== expectedHost) {
            throw new Error('External email body URL must be a tenant S3 URL generated by /upload-s3-files.');
        }

        const key = decodeURIComponent(parsed.pathname.replace(/^\/+/, ''));
        if (!key) {
            throw new Error('External email body URL is missing an S3 object key.');
        }

        return key;
    }

    async delete(s3Key) {
        if (!s3Key) {
            return;
        }

        await this.#s3Client.send(
            new DeleteObjectCommand({
                Bucket: this.#bucket,
                Key: s3Key,
            })
        );
    }

    async #bodyToBuffer(body) {
        if (!body) {
            return Buffer.alloc(0);
        }

        if (Buffer.isBuffer(body)) {
            return body;
        }

        if (typeof body === 'string') {
            return Buffer.from(body, 'utf8');
        }

        if (body instanceof Uint8Array) {
            return Buffer.from(body);
        }

        if (typeof body.transformToByteArray === 'function') {
            return Buffer.from(await body.transformToByteArray());
        }

        if (typeof body[Symbol.asyncIterator] === 'function') {
            const chunks = [];
            for await (const chunk of body) {
                chunks.push(Buffer.from(chunk));
            }
            return Buffer.concat(chunks);
        }

        return Buffer.from(String(body), 'utf8');
    }
}
