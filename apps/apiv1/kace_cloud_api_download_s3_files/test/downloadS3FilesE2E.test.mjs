import { uploadFileSchema } from '../src/schemas.mjs';

describe('DownloadS3FilesController test', () => {
    it('accepts uuid-prefixed email attachment filenames generated by S3AttachmentStorage', () => {
        const longOriginalFileName = `${'a'.repeat(251)}.pdf`;
        const storedFileName = `123e4567-e89b-12d3-a456-426614174000_${longOriginalFileName}`;

        const { error } = uploadFileSchema.validate({
            fileName: storedFileName,
            contentType: 'application/pdf',
            url: 'attachments',
            id: 'email-id',
        });

        expect(error).toBeUndefined();
    });
});
